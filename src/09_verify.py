"""Reproducibility proof: check inputs, outputs, and every number quoted in the docs and paper.

Writes docs/VERIFICATION.md and exits non-zero if any check fails. Run after run_all.sh:
    python3 src/09_verify.py
Checks
  1. Input integrity: SHA-256 of data/raw/extraction_packed.txt matches the value recorded
     at extraction time (24 Oct 2026).
  2. Data shape: cell, cell-year, scene and inventory counts match the paper.
  3. Headline estimates: recomputed from outputs/tables and compared with the values quoted
     in README.md, docs/methods.md and the paper (tolerance 0.0005 °C, i.e. the 3rd decimal).
  4. Paper integrity: every \\macro used in paper/main.tex is defined in paper/macros.tex,
     and macros.tex agrees with outputs/results.json.
  5. Output manifest: SHA-256 of every table, figure and the paper PDF.
"""
import hashlib, json, platform, re, sys, datetime
from pathlib import Path
import importlib.metadata as md

ROOT = Path(__file__).resolve().parents[1]
EXPECTED_SHA = "d79fc2ce2fb66ca3ae03093507041b17d91ea81ff214f9f4221aff548ba71686"
TOL = 0.0005 + 1e-9   # half a unit in the 3rd decimal, inclusive
checks = []

def check(name, ok, detail=""):
    checks.append((name, bool(ok), detail))

def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()

# 1. input integrity
raw = ROOT / "data/raw/extraction_packed.txt"
got = sha(raw) if raw.exists() else "missing"
check("Input SHA-256 matches extraction record", got == EXPECTED_SHA, f"`{got[:16]}…`")

# 2. data shape
R = json.load(open(ROOT / "outputs/results.json"))
d = R["data"]
for k, v in {"cells_90m": 15166, "scenes_searched": 151, "scenes_used": 111, "young_trees_le_1_5in": 5959,
             "young_trees_1_5_3in": 12612, "vacant_street_sites": 44469, "neighborhoods": 277}.items():
    check(f"Data count `{k}` = {v:,}", d[k] == v, f"found {d[k]:,}")

# 3. headline estimates vs quoted text
m = R["main_2022_25_vs_2006_09_per_tree"]["y15"]
rb = R["robustness_y15_2022_25"]
quoted = {   # value quoted in README / paper -> recomputed value
    "Main effect per young tree (−0.026)": (-0.026, m["b"]),
    "Main 95% CI lower (−0.047)": (-0.047, m["lo"]),
    "Main 95% CI upper (−0.005)": (-0.005, m["hi"]),
    "Pre-trend p (0.63)": (0.63, R["pretrend_y15"]["p"]),
    "Strictest controls (−0.027)": (-0.027, rb["all_site_types_x_year"]["b"]),
    "Unweighted (−0.028)": (-0.028, rb["unweighted"]["b"]),
    "Year FE only (−0.096)": (-0.096, rb["year_fe_only"]["b"]),
    "Sensitivity, 3× confounder (−0.024)": (-0.024, R["long_difference_sensitivity"]["bounds"][-1]["adjusted_estimate"]),
    "Binary young vs vacant (−0.089)": (-0.089, R["binary_young_vs_vacant_cells"]["b"]),
}
for name, (q, v) in quoted.items():
    tol = 0.005 if "p (" in name else TOL
    check(name, abs(q - v) <= tol, f"recomputed {v:+.4f}")
check("Neighborhood design fails pre-trend (p < 0.001)", R["csa_pilot"]["pretrend_p"] < 0.001,
      f"p = {R['csa_pilot']['pretrend_p']}")
readme = (ROOT / "README.md").read_text()
for s in ["−0.026 [−0.047, −0.005]", "−0.027 [−0.048, −0.006]", "−0.096 [−0.131, −0.060]", "p = 0.63"]:
    check(f"README quotes `{s}`", s in readme)

# 4. paper integrity
tex = (ROOT / "paper/main.tex").read_text()
macros_txt = (ROOT / "paper/macros.tex").read_text()
defined = set(re.findall(r"\\newcommand\{\\(\w+)\}", macros_txt)) | set(re.findall(r"\\newcommand\{\\(\w+)\}", tex))
used = set(re.findall(r"\\([A-Z][A-Za-z]+)\b", tex))
missing = sorted(u for u in used if u not in defined)
check("Every number macro in the paper is defined", not missing, ", ".join(missing) or "all defined")
mac = dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", macros_txt))
check("macros.tex main effect equals results.json", abs(float(mac["EstA"]) - m["b"]) <= TOL, f"EstA = {mac['EstA']}")
pdf = ROOT / "paper/Baltimore_Street_Trees_Cooling_Sahil_2026.pdf"
check("Paper PDF exists", pdf.exists())

# 5. manifest
files = sorted([p for p in (ROOT / "outputs").rglob("*") if p.is_file()]) + ([pdf] if pdf.exists() else []) + [raw]
manifest = [(str(p.relative_to(ROOT)), p.stat().st_size, sha(p)) for p in files]

passed = sum(ok for _, ok, _ in checks)
pkgs = {}
for p in ["numpy", "pandas", "pyfixest", "statsmodels", "scipy", "shapely", "matplotlib"]:
    try: pkgs[p] = md.version(p)
    except md.PackageNotFoundError: pkgs[p] = "not installed"
now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
L = [f"# Verification report", "",
     f"Generated by `src/09_verify.py` on {now}. **{passed} of {len(checks)} checks passed.**", "",
     "Re-run with `bash run_all.sh && python3 src/09_verify.py`. The GitHub Actions workflow "
     "(`.github/workflows/reproduce.yml`) does the same on a clean machine for every push.", "",
     "## Checks", "", "| Check | Result | Detail |", "|---|---|---|"]
L += [f"| {n} | {'PASS' if ok else '**FAIL**'} | {det} |" for n, ok, det in checks]
L += ["", "## Environment", "", f"- Python {platform.python_version()} on {platform.system()} {platform.machine()}"]
L += [f"- {k} {v}" for k, v in pkgs.items()]
L += ["", "## Output manifest (SHA-256)", "",
      "Figures are rendered by matplotlib and PDFs embed timestamps, so their hashes can differ between machines even when the "
      "numbers are identical. Tables and `results.json` are the canonical record.", "",
      "| File | Bytes | SHA-256 |", "|---|---:|---|"]
L += [f"| `{f}` | {b:,} | `{h}` |" for f, b, h in manifest]
(ROOT / "docs/VERIFICATION.md").write_text("\n".join(L) + "\n")
print(f"{passed}/{len(checks)} checks passed -> docs/VERIFICATION.md")
for n, ok, det in checks:
    if not ok: print("FAIL:", n, det)
sys.exit(0 if passed == len(checks) else 1)
