"""Write paper/macros.tex and paper/tab_*.tex from outputs/ (every number in the paper comes from here)."""
import json
import pandas as pd
from common import ROOT, RAW, TAB

P = ROOT / "paper"; P.mkdir(exist_ok=True)
r = json.load(open(ROOT / "outputs" / "results.json"))
es = json.load(open(TAB / "event_study_main.json"))
esy = pd.read_csv(TAB / "event_study_main.csv")
sc = pd.read_csv(RAW / "landsat_scenes.csv")

def n(x, d=3):          # signed number for LaTeX math, Unicode-free
    return f"{x:.{d}f}".replace("-", "-")
def c(x):               # thousands separator
    return f"{x:,}"
M = {}
d = r["data"]
M.update(NCells=c(es["n_cells"]), NGridCells=c(d["cells_90m"]), NCellYears=c(d["cell_years"]), NNbhd=d["neighborhoods"],
         NScenes=d["scenes_searched"], NScenesUsed=d["scenes_used"], NInventory="193,009",
         NYoungA=c(d["young_trees_le_1_5in"]), NYoungB=c(d["young_trees_1_5_3in"]), NMid=c(d["trees_3_6in"]),
         NMature=c(d["mature_gt_6in"]), NVacant=c(d["vacant_street_sites"]))
m = r["main_2022_25_vs_2006_09_per_tree"]
for k, nm in [("y15", "A"), ("y30", "B"), ("t36", "C"), ("vac", "V")]:
    M[f"Est{nm}"] = n(m[k]["b"]); M[f"Lo{nm}"] = n(m[k]["lo"]); M[f"Hi{nm}"] = n(m[k]["hi"])
M["EstAabs"] = f"{abs(m['y15']['b']):.3f}"; M["LoAabs"] = f"{abs(m['y15']['hi']):.3f}"; M["HiAabs"] = f"{abs(m['y15']['lo']):.3f}"
M["FiveTrees"] = f"{5*abs(m['y15']['b']):.2f}"
y15 = esy[esy.cohort == "y15"].set_index("year")
M["EstAtwentyfive"] = n(y15.loc[2025, "b"])
pt = r["pretrend_y15"]; M["PreWald"] = f"{pt['wald']:.2f}"; M["PreDf"] = pt["df"]; M["PreP"] = f"{pt['p']:.2f}"
rb = r["robustness_y15_2022_25"]
M["EstStrict"] = n(rb["all_site_types_x_year"]["b"]); M["LoStrict"] = n(rb["all_site_types_x_year"]["lo"]); M["HiStrict"] = n(rb["all_site_types_x_year"]["hi"])
M["EstYearFE"] = n(rb["year_fe_only"]["b"]); M["YearFERatio"] = f"{rb['year_fe_only']['b']/rb['main']['b']:.1f}"
pl = r["placebo_not_suitable_sites"]; M["EstPlacebo"] = n(pl["b"]); M["LoPlacebo"] = n(pl["lo"]); M["HiPlacebo"] = n(pl["hi"])
bi = r["binary_young_vs_vacant_cells"]
M.update(EstBin=n(bi["b"]), LoBin=n(bi["lo"]), HiBin=n(bi["hi"]), NBinT=c(bi["n_cells_treated"]), NBinC=c(bi["n_cells_control"]))
ld = r["long_difference_sensitivity"]
M.update(EstLD=n(ld["b"]), SeLD=f"{ld['se']:.4f}", RV=f"{100*ld['robustness_value_q1']:.1f}", RValpha=f"{100*ld['robustness_value_q1_alpha05']:.1f}",
         PartialRtwo=f"{100*ld['partial_r2_treat']:.2f}")
b3 = ld["bounds"][-1]; M.update(EstAdjThree=n(b3["adjusted_estimate"]), LoAdjThree=n(b3["adjusted_lo"]), HiAdjThree=n(b3["adjusted_hi"]))
cs = r["csa_pilot"]
M.update(NCSA=cs["n_csa"], CSATrees=c(cs["trees_2013_2020_total"]), CSAPreWald=f"{cs['pretrend_wald_2009_2012']:.0f}",
         CSADoseMean=f"{cs['dose_mean_per_km2']:.0f}", CSALate=n(cs["mean_coef_2021_2025_per_100_trees_km2"], 2),
         CSAPre=n(cs["mean_coef_2009_2012_pre"], 2))
used = sc[sc.used.astype(str).str.lower() == "true"]
M["ScenesPerYearMin"] = int(used.date.str[:4].value_counts().min()); M["ScenesPerYearMax"] = int(used.date.str[:4].value_counts().max())
with open(P / "macros.tex", "w") as f:
    f.write("% generated by src/08_tex.py — do not edit by hand\n")
    for k, v in M.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

# Table: pooled period estimates by cohort
labels = {"y15": "Young, DBH $\\le$ 1.5 in", "y30": "Young, DBH 1.5--3 in", "t36": "DBH 3--6 in", "vac": "Vacant plantable site"}
rows = []
for k in ("y15", "y30", "t36", "vac"):
    cells = []
    for p in ("2010_2013", "2014_2017", "2018_2021", "2022_2025"):
        e = es[k][p]; star = "^{*}" if (e["lo"] > 0 or e["hi"] < 0) else ""
        cells.append(f"${e['b']:.3f}{star}$ {{\\footnotesize $({e['se']:.3f})$}}".replace("$-0.000", "$0.000"))
    rows.append(f"{labels[k]} & " + " & ".join(cells) + " \\\\")
open(P / "tab_main.tex", "w").write("\n".join(rows) + "\n")

# Table: robustness
names = {"main": "Main specification", "all_site_types_x_year": "All site types $\\times$ year (strictest controls)",
         "no_controls": "No site-type controls", "unweighted": "Unweighted", "cluster_csa": "Clustered by 55 CSAs",
         "min_3_scenes": "Cell-years with $\\ge$3 clear scenes", "no_park_cells": "Excluding cells with park trees",
         "year_fe_only": "Year FE only (no neighborhood $\\times$ year FE)"}
rob = json.load(open(TAB / "robustness.json"))
lines = []
for k, lab in names.items():
    v = rob[k]
    lines.append(lab + " & " + " & ".join(f"${v[cc]['b']:.3f}$ {{\\footnotesize $[{v[cc]['lo']:.3f}, {v[cc]['hi']:.3f}]$}}" for cc in ("y15", "y30", "t36")) + " \\\\")
open(P / "tab_robust.tex", "w").write("\n".join(lines) + "\n")

# Table: sensitivity bounds
sl = []
for bnd in ld["bounds"]:
    sl.append(f"{bnd['kd']}$\\times$ mature-tree density & {100*bnd['r2dz_x']:.2f} & {100*bnd['r2yz_dx']:.2f} & ${bnd['adjusted_estimate']:.3f}$ & $[{bnd['adjusted_lo']:.3f}, {bnd['adjusted_hi']:.3f}]$ \\\\")
open(P / "tab_sens.tex", "w").write("\n".join(sl) + "\n")

# Table: scenes by year and sensor (appendix)
sc["year"] = sc.date.astype(str).str[:4]
u = sc[sc.used.astype(str).str.lower() == "true"]
t = u.groupby(["year", "platform"]).size().unstack(fill_value=0)
t = t.reindex(columns=["landsat-5", "landsat-7", "landsat-8", "landsat-9"], fill_value=0)
yrs = list(t.index); half = (len(yrs) + 1) // 2
def row(y): return f"{y} & " + " & ".join(str(int(x)) for x in t.loc[y]) + f" & {int(t.loc[y].sum())}"
L = []
for i in range(half):
    a = row(yrs[i]); b = row(yrs[i + half]) if i + half < len(yrs) else " & & & & & "
    L.append(a + " & " + b + " \\\\")
open(P / "tab_scenes.tex", "w").write("\n".join(L) + "\n")
print(f"wrote {len(M)} macros and 4 tables")

# cosmetic: never print a negative zero
for f in P.glob("tab_*.tex"):
    f.write_text(f.read_text().replace("$-0.000", "$0.000").replace("[-0.000", "[0.000").replace(" -0.000]", " 0.000]"))
